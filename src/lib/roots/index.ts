import rootData from "./rootData.json";

/*
  Hebrew root lookup. Data is generated by scripts/roots (see its README):
  Open Scriptures BDB lexical index + OSHB augmented Strong's numbers, CC BY 4.0.

  A word's root depends on its Strong's number and, for the few Strong's numbers that cover
  several unrelated roots (homonyms such as ענה "answer" / "sing"), on which homonym this
  occurrence is. Those occurrences are listed in `exceptions`, keyed by verse (heb_bible's
  English numbering) and by the word's position among same-Strong's words in that verse.
*/

type RootData = {
  /** [pointed word (tooltip), English sense, homonym numeral or "", bare root letters or "", English qualifier?] */
  roots: [string, string, string, string?, string?][];
  strong: Record<string, number>;
  /** dictionary form + gloss (+ English qualifier) for words without a root */
  lemmas: Record<string, [string, string, string?]>;
  exceptions: Record<string, number>;
  /** proper names: left out of Repeated Roots */
  names: number[];
  /** dictionary words written as several words (אַל־תַּשְׁחֵת): their rows make one occurrence */
  compounds: number[];
};

const data = rootData as unknown as RootData;
const NAMES = new Set(data.names);
const COMPOUNDS = new Set(data.compounds);

export type RootRef = {
  /** Root group id, e.g. "r42". */
  id: string;
  /** A pointed word from the root's family, shown in the chip's tooltip: the verb's qatal
   *  (יָשַׁב, דִּבֵּר) when the verb is common, otherwise its most common word (לֵב, מַיִם). */
  label: string;
  /** Short English sense, e.g. "sit". */
  gloss?: string;
  /** BDB homonym numeral ("I", "II"...) for telling identically spelled roots apart, if any. */
  homonym?: string;
  /** Bare root letters with shin/sin dot (ישׁב), shown on the chip; absent for single words. */
  letters?: string;
  /** English qualifier used when two chips share an English label ("assemble" in "to gather (assemble)"). */
  qualifier?: string;
};

export type RootInfo = {
  /** The word's root group. Undefined for particles and unrooted words (exact match only). */
  root?: RootRef;
  /** Dictionary form and gloss, for words without a root (כִּי, names). */
  lemma?: string;
  lemmaGloss?: string;
  /** English qualifier for lemmaGloss, see RootRef.qualifier. */
  lemmaQualifier?: string;
  /** Proper name: not part of Repeated Roots. */
  isName?: boolean;
};

/** True for a dictionary word written as several words (אַל־תַּשְׁחֵת, יְפֵה־פִיָּה), whose parts are
 *  separate heb_bible rows with the same Strong's number. */
export function isCompoundWord(strongNumber: number): boolean {
  return COMPOUNDS.has(strongNumber);
}

function rootRef(index: number | undefined): RootRef | undefined {
  if (index === undefined || index < 0 || !data.roots[index]) {
    return undefined;
  }
  const [label, gloss, homonym, letters, qualifier] = data.roots[index];
  return {
    id: `r${index}`,
    label,
    gloss: gloss || undefined,
    homonym: homonym || undefined,
    letters: letters || undefined,
    qualifier: qualifier || undefined,
  };
}

/**
 * @param book       heb_bible book name, e.g. "psalms"
 * @param nthInVerse 0-based count of earlier words in the same verse with the same Strong's number
 */
export function lookupRoot(
  book: string,
  chapter: number,
  verse: number,
  strongNumber: number,
  nthInVerse: number
): RootInfo {
  if (!strongNumber) {
    return {};
  }
  const exceptionKey = `${book.toLowerCase()}|${chapter}|${verse}|${strongNumber}|${nthInVerse}`;
  const index = exceptionKey in data.exceptions
    ? data.exceptions[exceptionKey]
    : data.strong[String(strongNumber)];
  const root = rootRef(index);
  const lemma = root ? undefined : data.lemmas[String(strongNumber)];
  return {
    root,
    lemma: lemma?.[0] || undefined,
    lemmaGloss: lemma?.[1] || undefined,
    lemmaQualifier: lemma?.[2] || undefined,
    isName: NAMES.has(strongNumber) || undefined,
  };
}
